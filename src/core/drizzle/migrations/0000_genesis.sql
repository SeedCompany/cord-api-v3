-- Name: sync_project_step_from_event(); Type: FUNCTION; Schema: public; Owner: -
--

CREATE FUNCTION public.sync_project_step_from_event() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
  UPDATE "projects"
     SET "step"            = NEW."to_step",
         "modified_at"     = NEW."at",
         "step_changed_at" = NEW."at"
   WHERE "id" = NEW."project_id"
     AND NOT EXISTS (
       SELECT 1 FROM "project_workflow_events" "e"
       WHERE "e"."project_id" = NEW."project_id"
         AND ("e"."at", "e"."id") > (NEW."at", NEW."id")
     );
  RETURN NEW;
END;
$$;

